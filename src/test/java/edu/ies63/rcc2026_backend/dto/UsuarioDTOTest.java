package edu.ies63.rcc2026_backend.dto;

import edu.ies63.rcc2026_backend.enums.Role;
import org.junit.jupiter.api.Test;

import java.util.List;

import static org.junit.jupiter.api.Assertions.*;

class UsuarioDTOTest {

  @Test
  void testUsuarioCreateDTO() {
    UsuarioCreateDTO dto = new UsuarioCreateDTO(
        "user@test.com", "pass123", "Usuario Nuevo", "Bio", 10L
    );

    assertEquals("user@test.com", dto.username());
    assertEquals("pass123", dto.password());
    assertEquals("Usuario Nuevo", dto.nombre());
    assertEquals("Bio", dto.biografia());
    assertEquals(10L, dto.localidadId());
  }

  @Test
  void testUsuarioResponseDTO() {
    UsuarioResponseDTO dto = new UsuarioResponseDTO(
        1L, "user@test.com", Role.USUARIO, "User", "Bio"
    );

    assertEquals(1L, dto.id());
    assertEquals("user@test.com", dto.username());
    assertEquals(Role.USUARIO, dto.role());
  }

  @Test
  void testPerfilResponseDTO() {
    PerfilResponseDTO dto = new PerfilResponseDTO(
        1L, "admin@test.com", Role.ADMIN, "Admin", "Bio Admin", "Director",
        5L, "Posadas, MISIONES", "123456", List.of(), List.of()
    );

    assertEquals("Director", dto.director());
    assertEquals(5L, dto.localidadId());
    assertEquals("Posadas, MISIONES", dto.localidadStr());
    assertTrue(dto.imagenesPerfil().isEmpty());
    assertTrue(dto.redes().isEmpty());
  }

  @Test
  void testPerfilUpdateDTO() {
    PerfilUpdateDTO dto = new PerfilUpdateDTO(
        "Nombre Update", "Bio Update", "Director Update", "111222",
        "mi_insta", "mi_face", "mi_x", null, null
    );

    assertEquals("Nombre Update", dto.nombre());
    assertEquals("mi_insta", dto.instagram());
    assertNull(dto.fotoPerfil());
    assertNull(dto.fotoBanner());
  }

  @Test
  void testRecordsAutogeneratedMethods() {
    UsuarioCreateDTO dto1 = new UsuarioCreateDTO("a@a.com", "123", "A", "B", 1L);
    UsuarioCreateDTO dto2 = new UsuarioCreateDTO("a@a.com", "123", "A", "B", 1L);

    // Dispara la cobertura de equals(), hashCode() y toString() generada por el Record
    assertEquals(dto1, dto2);
    assertEquals(dto1.hashCode(), dto2.hashCode());
    assertTrue(dto1.toString().contains("a@a.com"));
  }
}